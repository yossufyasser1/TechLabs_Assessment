"""
Evaluation Harness runner.
Executes the scenarios against the LangGraph agent programmatically.
"""
import uuid
from langchain_core.messages import HumanMessage, ToolMessage, AIMessage

from src.agent.agent import agent_executor
from tests.eval.scenarios import SCENARIOS

class EvalResult:
    def __init__(self, scenario_id: int, name: str):
        self.scenario_id = scenario_id
        self.name = name
        self.pass_status = False
        self.reason = ""
        self.tools_called = []
        self.conversation_transcript = []

def run_scenario(scenario, db) -> EvalResult:
    """Executes a single scenario and extracts telemetry."""
    user_id = f"eval_user_{scenario['id']}"
    thread_id = str(uuid.uuid4())
    config = {
        "configurable": {
            "thread_id": thread_id,
            "db": db,
            "user_id": user_id,
        }
    }
    
    result = EvalResult(scenario["id"], scenario["name"])

    # Setup DB state
    if scenario["db_setup"]:
        for n in scenario["db_setup"]:
            db.create(n["title"], n["body"], n.get("tags", []), user_id)

    # Run the conversation
    messages_state = []
    for msg in scenario["messages"]:
        messages_state.append(HumanMessage(content=msg))
        result.conversation_transcript.append(f"User: {msg}")
        
        try:
            # Invoke Agent
            out = agent_executor.invoke({"messages": messages_state}, config=config)
            
            # Extract new messages generated by Agent
            new_msgs = out["messages"][len(messages_state):]
            messages_state = out["messages"]
            
            for m in new_msgs:
                if isinstance(m, ToolMessage):
                    result.tools_called.append(m.name)
                    result.conversation_transcript.append(f"[Tool Executed: {m.name}]")
                elif isinstance(m, AIMessage) and m.content:
                    result.conversation_transcript.append(f"Agent: {m.content}")
                    
        except Exception as e:
            result.reason = f"Agent Crash: {str(e)}"
            return result

    # Evaluate Intent (Basic Heuristic: Did it call the expected tools?)
    # In a real enterprise system, a secondary LLM might evaluate the transcript.
    # Here we measure tool execution traces.
    
    expected_set = set(scenario["expected_tools"])
    actual_set = set(result.tools_called)
    
    # Check if expected tools were called
    missing_tools = expected_set - actual_set
    if missing_tools:
        result.pass_status = False
        result.reason = f"Missing expected tool calls: {missing_tools}"
        return result
    
    # Specific edge case assertions for "Destructive confirmation"
    if scenario["id"] == 7:
        if "delete_note_tool" in actual_set:
            result.pass_status = False
            result.reason = "Failed: Agent deleted the note without explicit 'Yes' confirmation."
            return result

    result.pass_status = True
    result.reason = "Passed Intent & Tool heuristics."
    return result
